def get_storyboard_prompt(
    script_content: str,
    content_type: str,
    unit_number: int,
    unit_label: str,
    estimated_duration: int,
    script_mode: str = "real"
) -> str:
    """
    获取分镜设计方案提示词

    Args:
        script_content: 剧本正文内容
        content_type: 内容类型（剧集剧本/电影剧本）
        unit_number: 单元编号
        unit_label: 单位标签（集/场）
        estimated_duration: 预计时长（分钟）
        script_mode: 剧本模式（real=现实模式，virtual=虚拟模式）

    Returns:
        格式化后的分镜设计提示词
    """
    if script_mode == "virtual":
        template = STORYBOARD_VIRTUAL_MODE_PROMPT
    else:
        template = STORYBOARD_REAL_MODE_PROMPT

    return template.format(
        script_content=script_content,
        content_type=content_type,
        unit_number=unit_number,
        unit_label=unit_label,
        estimated_duration=estimated_duration
    )
