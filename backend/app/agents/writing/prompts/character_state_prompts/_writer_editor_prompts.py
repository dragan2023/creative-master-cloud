def format_state_change_table(
    state_changes: list,
    content_type: str = "novel"
) -> str:
    """格式化状态变化表格"""
    if not state_changes:
        return "本章/场无重要人物状态变化"

    rows = []
    for change in state_changes:
        row = CHARACTER_STATE_PROMPTS["state_change_row"].format(
            character=change.get("character", ""),
            change_type=STATE_CHANGE_TYPES.get(
                change.get("change_type", "other"), "其他变化"),
            before=change.get("before", ""),
            after=change.get("after", ""),
            reason=change.get("reason", ""),
            evidence=change.get("evidence", "")
        )
        rows.append(row)

    return CHARACTER_STATE_PROMPTS["state_change_template"].format(
        state_change_rows="\n".join(rows)
    )
