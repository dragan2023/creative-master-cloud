def get_title_style_guidance(title_style_id: str, title_style_name: str = "") -> str:
    """
    获取标题风格指导文本

    Args:
        title_style_id: 标题风格ID
        title_style_name: 标题风格中文名称（可选，用于回退）

    Returns:
        标题风格指导文本，如果未提供或找不到则返回空字符串
    """
    if not title_style_id:
        return ""

    # 从映射表中获取指导文本
    guidance = TITLE_STYLE_GUIDANCE.get(title_style_id, "")

    if guidance:
        return guidance

    # 如果找不到精确匹配，使用默认指导
    if title_style_name:
        return f"""
## 章节标题风格：{title_style_name}

请根据"{title_style_name}"的风格特点为章节命名。
确保所有章节标题都符合此风格的特征和要求。
"""

    return ""


def get_all_title_styles() -> list:
    """
    获取所有可用的标题风格列表

    Returns:
        标题风格列表，每个元素包含id和name
    """
    styles = []
    for style_id, guidance in TITLE_STYLE_GUIDANCE.items():
        # 从指导文本中提取风格名称
        first_line = guidance.strip().split('\n')[0]
        style_name = first_line.replace('## 章节标题风格：', '').split('（')[0].strip()
        styles.append({
            'id': style_id,
            'name': style_name
        })
    return styles
