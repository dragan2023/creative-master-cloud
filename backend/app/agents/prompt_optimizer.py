class PromptOptimizer:
    """提示词优化器"""

    def __init__(self):
        self.logger = get_logger("prompt_optimizer")
        self.llm_manager = get_llm_manager()

    def get_supported_modules(self) -> Dict[str, str]:
        """获取支持的模块列表"""
        return {
            module: info["name"]
            for module, info in OPTIMIZER_PROMPTS.items()
        }

    async def optimize(
        self,
        db: AsyncSession,
        user_id: int,
        module: str,
        original_text: str
    ) -> Dict[str, Any]:
        """
        执行提示词优化

        Args:
            db: 数据库会话
            user_id: 用户ID
            module: 模块名称（short_video/script/novel/print_ad/tvc）
            original_text: 原始描述文本

        Returns:
            优化结果字典，包含:
            - optimized_text: 优化后的文本
            - original_length: 原始文本长度
            - optimized_length: 优化后文本长度
        """
        # 验证模块
        if module not in OPTIMIZER_PROMPTS:
            raise ValueError(
                f"不支持的模块: {module}，支持的模块: {list(OPTIMIZER_PROMPTS.keys())}")

        # 验证输入
        if not original_text or len(original_text.strip()) < 5:
            raise ValueError("原始描述太短，请至少输入5个字符")

        # 获取优化提示词模板
        template = OPTIMIZER_PROMPTS[module]
        prompt = template["content"].format(
            original_text=original_text.strip())

        self.logger.info(
            f"开始优化提示词 - 模块: {module}, 用户: {user_id}, 原文长度: {len(original_text)}")

        try:
            # 获取LLM提供者（优先用户DB配置，回退系统预置）
            provider = await self._get_provider_with_fallback(db, user_id)

            # 构建系统提示词
            system_prompt = (
                "你是一个专业的提示词优化助手，擅长将用户的创意描述优化为结构化、详细的创作需求。"
                "请严格按照模板格式输出，确保优化结果完整、清晰、可直接用于创作。"
            )

            # 调用LLM进行优化
            response = await provider.generate(
                prompt=prompt,
                system_prompt=system_prompt,
                temperature=0.7,
                module_name="prompt_optimizer"
            )

            optimized_text = response.content.strip()

            self.logger.info(f"优化完成 - 优化后长度: {len(optimized_text)}")

            return {
                "optimized_text": optimized_text,
                "original_length": len(original_text),
                "optimized_length": len(optimized_text),
                "module": module,
                "module_name": template["name"]
            }

        except Exception as e:
            self.logger.error(f"优化失败: {str(e)}")
            raise Exception(f"提示词优化失败: {str(e)}")

    async def _get_provider_with_fallback(self, db, user_id):
        """
        获取LLM提供者，带多层回退机制：
        1. 优先使用用户DB配置的默认LLM
        2. 回退到系统预置provider（qianwen → doubao → siliconflow → t8star → deepseek）
        """
        try:
            provider = await self.llm_manager.get_provider_from_db(db, user_id)
            if provider:
                self.logger.info(f"使用用户配置的LLM提供者: {provider.model_name}")
                return provider
        except Exception as e:
            self.logger.warning(f"用户配置的LLM提供者获取失败: {e}，尝试系统预置")

        # 回退：按优先级尝试系统预置provider
        fallback_providers = ["qianwen", "doubao", "siliconflow", "t8star", "deepseek"]
        last_error = None
        for provider_name in fallback_providers:
            try:
                provider = await self.llm_manager.get_system_provider(provider_name)
                if provider:
                    self.logger.info(f"使用系统预置LLM提供者 [{provider_name}]: {provider.model_name}")
                    return provider
            except Exception as e:
                last_error = e
                self.logger.debug(f"系统预置provider [{provider_name}] 不可用: {e}")
                continue

        raise Exception(f"无法获取可用的LLM提供者，所有回退均失败。最后错误: {last_error}")


# 全局优化器实例
prompt_optimizer = PromptOptimizer()


def get_prompt_optimizer() -> PromptOptimizer:
    """获取提示词优化器实例"""
    return prompt_optimizer
